-- Live organizations table (post migration 031)

CREATE TABLE organizations (
  id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name                VARCHAR(255) NOT NULL,
  slug                VARCHAR(100) UNIQUE NOT NULL,
  legal_name          VARCHAR(255),
  owner_name          VARCHAR(255) NOT NULL,
  owner_email         VARCHAR(255) NOT NULL,
  owner_phone         VARCHAR(20),
  gst_number          VARCHAR(50),
  pan_number          VARCHAR(20),
  logo_url            TEXT,
  kyc_document_url    TEXT,
  gst_certificate_url TEXT,
  photo_url           TEXT,
  registered_address  JSONB NOT NULL,
  state_id            UUID NOT NULL REFERENCES states(id),
  campaign_attribution JSONB,
  business_type       VARCHAR(30),
  cin                 VARCHAR(21),
  udyam_msme_number   VARCHAR(20),
  gst_registration_type VARCHAR(20),
  kyc_status          VARCHAR(20) NOT NULL DEFAULT 'NOT_SUBMITTED',
  kyc_verified_at     TIMESTAMPTZ,
  kyc_verified_by     UUID REFERENCES super_admin_users(id),
  signed_agreement_url TEXT,
  is_agreement_signed BOOLEAN NOT NULL DEFAULT FALSE,
  status              VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  status_reason_id    UUID REFERENCES reason_codes(id),
  status_notes        TEXT,
  status_changed_at   TIMESTAMPTZ,
  status_changed_by   UUID REFERENCES super_admin_users(id),
  suspended_at        TIMESTAMPTZ,
  resumed_at          TIMESTAMPTZ,
  terminated_at       TIMESTAMPTZ,
  onboarded_at        TIMESTAMPTZ,
  approved_at         TIMESTAMPTZ,
  approved_by         UUID REFERENCES super_admin_users(id),
  owner_portal_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  owner_last_login_at TIMESTAMPTZ,
  owner_disabled_at   TIMESTAMPTZ,
  owner_disabled_by   UUID REFERENCES super_admin_users(id),
  created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
